//! Ledger replay and comparison (kernel.md sections 2 and 9; clauses 6.6, 8.4 and 8.5; task 2.4,
//! case CWR-010).
//!
//! `cwr instance replay` recreates an Instance from the inputs that define it and nothing else:
//! the seed, tail size, arm and model in the original ledger's header, the initial state named by
//! the header's `initial_state` hash, the Build named by the header's `build` hash, the cassette of
//! the original's adapter traffic and the script of every turn as recorded by the kernel when the
//! turn was run ([`record_script`]). It re-runs every turn's script through the real kernel (fresh
//! sandbox, atomic contract check, gateway in replay mode, so no socket is opened) and compares the
//! new ledger with the original record by record, ignoring only host fields: `host_ts`,
//! `duration_us` and `instance` (the new Instance's ULID, whose time component is host time and
//! which the chain and `world.history` already exclude). The first divergent record is a
//! determinism defect: it is reported with both values and the new Instance is sealed.
//!
//! A model message accepted by the turn protocol is replayed from its extracted script like any
//! other turn. A message the protocol refused is replayed from the refusal marker the kernel
//! records with it ([`record_refusal`]): the rule it broke and the fence lines, never the message
//! text, which the turn protocol never records. Replay re-applies the refusal, reproducing the
//! identical `turn.protocol` record. A probe turn is
//! replayed from its recorded call list ([`record_probe`]). Each turn number has exactly one
//! recorded input: recording one removes any other recorded for the same number, which only a
//! submission refused before its turn began or a turn abandoned by a restore can have left.
//! Drift records of an `--x-drift` Build are regenerated by the replayed turns and compared like
//! any other record.
//!
//! Lifecycle records are re-applied, in ledger order between the turns, through the kernel
//! operation that wrote them. An `upgrade` record upgrades the replay Instance to the Build it
//! names (its `new_build` hash, resolved in [`ReplayInputs::builds`] and beside the replayed
//! Build), which re-runs the migrations and stores the recompile notice. A `recovery` record
//! written by a restore snapshots the replay Instance and restores that snapshot. Both records
//! name a snapshot file, whose bytes carry the Instance id and chain of the Instance that took it,
//! so the comparison checks the replay's snapshot under the original id and chain instead of its
//! file hash, and recomputes the chain of every later replayed record accordingly
//! ([`as_original`]). The `abandoned_from` and `retained` fields of a `recovery` record describe
//! records outside the live lineage, which replay does not re-run; they are taken from the
//! original. A `recovery` record that closes a turn interrupted by a kernel crash
//! (`interrupted_turn` set) is refused before anything is created: replay re-runs complete turns
//! and cannot reproduce where a crash cut one.
//!
//! The original ledger is read strictly before anything is created: a truncated record, a seq gap
//! or any record that fails the hash chain is refused, and so is a header whose Build or initial
//! state does not match the inputs. A ledger edited and re-chained passes that check but cannot
//! survive the comparison, because the replay produces what the world actually does.
//!
//! The only Instance inputs replay and comparison read are the ledger and the state (clause 8.5);
//! kernel internals (metadata, envelopes, sandbox output, gateway store, raw payloads) are never
//! consulted.

