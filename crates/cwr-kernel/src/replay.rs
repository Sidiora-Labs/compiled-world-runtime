/// Directory of recorded turn scripts inside an Instance directory.
pub const SCRIPTS_DIR: &str = "scripts";
/// Record fields a replay comparison ignores (host-derived).
pub const IGNORED_FIELDS: [&str; 3] = ["host_ts", "duration_us", "instance"];
/// Record kinds a replay reproduces. The first six are written by a turn, which replay re-runs;
/// `drift` records are written by the turn itself on an `--x-drift` Build (executed or refused).
/// `upgrade` and `recovery` are lifecycle events applied between turns, which replay re-applies
/// through the same kernel operations.
pub const REPLAYABLE_KINDS: [&str; 8] = [
    "header",
    "primitive",
    "adapter",
    "proposal",
    "turn",
    "drift",
    "upgrade",
    "recovery",
];
/// Fields of a `recovery` record that describe records outside the live lineage (where the
/// abandoned records began and the file that retains them). Replay re-runs only the live lineage,
/// so these fields are taken from the original record when the ledgers are compared.
pub const LINEAGE_FIELDS: [&str; 2] = ["abandoned_from", "retained"];

/// Path of the protocol-refusal marker of `turn` in a scripts directory, present for every turn
/// the turn protocol refused.
pub fn refusal_file(scripts_dir: &Path, turn: u64) -> PathBuf {
    scripts_dir.join(format!("turn-{turn:06}.refusal.json"))
}

/// The refusal marker of `violation`: the rule broken and its fence lines, no message text.
pub fn violation_to_json(violation: &Violation) -> Value {
    match violation {
        Violation::NoBlock => json!({"violation": "no_block"}),
        Violation::MultipleBlocks { lines } => {
            json!({"violation": "multiple_blocks", "lines": lines})
        }
        Violation::WrongLanguage { language, line } => {
            json!({"violation": "wrong_language", "language": language, "line": line})
        }
        Violation::UnclosedFence { line } => json!({"violation": "unclosed_fence", "line": line}),
    }
}

/// The violation a refusal marker records, or `None` when the marker is malformed.
pub fn violation_from_json(v: &Value) -> Option<Violation> {
    let line = || v["line"].as_u64().map(|n| n as usize);
    match v["violation"].as_str()? {
        "no_block" => Some(Violation::NoBlock),
        "multiple_blocks" => Some(Violation::MultipleBlocks {
            lines: v["lines"]
                .as_array()?
                .iter()
                .map(|n| n.as_u64().map(|n| n as usize))
                .collect::<Option<Vec<_>>>()?,
        }),
        "wrong_language" => Some(Violation::WrongLanguage {
            language: v["language"].as_str()?.to_string(),
            line: line()?,
        }),
        "unclosed_fence" => Some(Violation::UnclosedFence { line: line()? }),
        _ => None,
    }
}

/// Path of the recorded call list of probe turn `turn` in a scripts directory.
pub fn probe_file(scripts_dir: &Path, turn: u64) -> PathBuf {
    scripts_dir.join(format!("turn-{turn:06}.probe.json"))
}

/// Records, durably and before the refusal is appended, that the turn protocol refuses the next
/// turn of `inst` for `violation`, so that replay reproduces the refusal record.
pub fn record_refusal(inst: &Instance, violation: &Violation) -> Result<PathBuf> {
    record_input(
        inst,
        refusal_file,
        canonical_json(&violation_to_json(violation)).as_bytes(),
    )
}

/// Records the calls of the next turn of `inst` as a probe turn, durably, before it runs.
pub fn record_probe(inst: &Instance, calls: &[ProbeCall]) -> Result<PathBuf> {
    let list: Vec<Value> = calls
        .iter()
        .map(|c| json!({"primitive": c.primitive, "params": c.params}))
        .collect();
    record_input(
        inst,
        probe_file,
        canonical_json(&Value::Array(list)).as_bytes(),
    )
}

/// Writes `bytes` durably as the one recorded input of the next turn of `inst`, at
/// `path(scripts_dir, turn)`, after removing any other input recorded for that turn number. A
/// turn number is recorded again only after a submission that never began its turn (refused
/// before it started) or after a restore abandoned the turn, so the latest input is the one the
/// live ledger's turn record belongs to.
fn record_input(inst: &Instance, path: fn(&Path, u64) -> PathBuf, bytes: &[u8]) -> Result<PathBuf> {
    let dir = inst.dir.join(SCRIPTS_DIR);
    std::fs::create_dir_all(&dir).map_err(|e| crate::io_err("create", &dir, e))?;
    let turn = inst.meta.turn + 1;
    let p = path(&dir, turn);
    for other in [
        refusal_file(&dir, turn),
        probe_file(&dir, turn),
        script_file(&dir, turn),
    ] {
        if other == p {
            continue;
        }
        match std::fs::remove_file(&other) {
            Ok(()) => {}
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => return Err(crate::io_err("remove", &other, e)),
        }
    }
    write_atomic(&p, bytes)?;
    Ok(p)
}

fn read_probe(p: &Path) -> Result<Vec<ProbeCall>> {
    let text = std::fs::read_to_string(p).map_err(|e| crate::io_err("read", p, e))?;
    let v: Value = serde_json::from_str(&text)
        .map_err(|e| refuse(format!("{} is not JSON: {e}", p.display())))?;
    let calls = v
        .as_array()
        .ok_or_else(|| refuse(format!("{} is not a list of calls", p.display())))?;
    calls
        .iter()
        .map(|c| match (c["primitive"].as_str(), c.get("params")) {
            (Some(name), Some(params)) => Ok(ProbeCall {
                primitive: name.to_string(),
                params: params.clone(),
            }),
            _ => Err(refuse(format!(
                "{} holds a call without primitive and params",
                p.display()
            ))),
        })
        .collect()
}

/// What a turn was submitted as, recovered from the recorded inputs.
enum TurnInput {
    /// A raw script (`--script` or standard input).
    Script(String),
    /// A message the turn protocol refused.
    Refusal(Violation),
    /// A kernel-direct probe turn.
    Probe(Vec<ProbeCall>),
}

/// The recorded input of `turn` under `scripts_dir`: a protocol-refusal marker, a probe call list
/// or a script. `turn_record` is the original's `turn` record, used only to say what is missing.
fn turn_input(scripts_dir: &Path, turn: u64, turn_record: Option<&Value>) -> Result<TurnInput> {
    let m = refusal_file(scripts_dir, turn);
    if m.is_file() {
        let text = std::fs::read_to_string(&m).map_err(|e| crate::io_err("read", &m, e))?;
        let v = serde_json::from_str::<Value>(&text)
            .ok()
            .and_then(|v| violation_from_json(&v))
            .ok_or_else(|| refuse(format!("{} is not a refusal marker", m.display())))?;
        return Ok(TurnInput::Refusal(v));
    }
    let p = probe_file(scripts_dir, turn);
    if p.is_file() {
        return Ok(TurnInput::Probe(read_probe(&p)?));
    }
    let s = script_file(scripts_dir, turn);
    if s.is_file() {
        let text = std::fs::read_to_string(&s).map_err(|e| crate::io_err("read", &s, e))?;
        return Ok(TurnInput::Script(text));
    }
    let protocol = turn_record.is_some_and(|r| r["primitive"] == PROTOCOL_PRIMITIVE);
    Err(refuse(if protocol {
        format!(
            "turn {turn} was a protocol refusal and its refusal marker was not recorded (expected {})",
            m.display()
        )
    } else {
        format!(
            "turn {turn} has no recorded input: none of {}, {} or {} exists",
            m.display(),
            p.display(),
            s.display()
        )
    }))
}

/// Path of the recorded script of `turn` in Instance directory `dir`.
pub fn script_path(dir: &Path, turn: u64) -> PathBuf {
    script_file(&dir.join(SCRIPTS_DIR), turn)
}

/// Path of the script of `turn` in a scripts directory.
pub fn script_file(scripts_dir: &Path, turn: u64) -> PathBuf {
    scripts_dir.join(format!("turn-{turn:06}.py"))
}

/// Records `script` as the script of the next turn of `inst`, durably, before the turn runs.
pub fn record_script(inst: &Instance, script: &str) -> Result<PathBuf> {
    record_input(inst, script_file, script.as_bytes())
}

/// The first difference between two ledgers.
#[derive(Debug, Clone, PartialEq)]
pub struct Divergence {
    /// Seq of the first record that differs.
    pub seq: u64,
    /// The first differing field in sorted order (`chain` last), or `<record>` for a missing record.
    pub field: String,
    /// The field's value in the original ledger, or `"<absent>"`.
    pub original: Value,
    /// The field's value in the replayed ledger, or `"<absent>"`.
    pub replayed: Value,
}

impl Divergence {
    /// The divergence as `{seq, field, original, replayed}`.
    pub fn to_json(&self) -> Value {
        json!({"seq": self.seq, "field": self.field, "original": self.original, "replayed": self.replayed})
    }
}

impl std::fmt::Display for Divergence {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "first divergent record seq {} field {}: original {} replayed {}",
            self.seq,
            self.field,
            canonical_json(&self.original),
            canonical_json(&self.replayed)
        )
    }
}

/// A record without the ignored host fields.
pub fn comparable(r: &Value) -> Value {
    let mut r = r.clone();
    if let Value::Object(m) = &mut r {
        for f in IGNORED_FIELDS {
            m.remove(f);
        }
    }
    r
}

/// The first field (in sorted order) where two records differ, ignoring host fields.
fn field_diff(seq: u64, a: &Value, b: &Value) -> Option<Divergence> {
    let (a, b) = (comparable(a), comparable(b));
    if a == b {
        return None;
    }
    let (Some(am), Some(bm)) = (a.as_object(), b.as_object()) else {
        return Some(Divergence {
            seq,
            field: "<record>".into(),
            original: a,
            replayed: b,
        });
    };
    let mut keys: Vec<&String> = am.keys().chain(bm.keys()).collect();
    keys.sort();
    keys.dedup();
    // `chain` is derived from every other field: report the substantive field first.
    keys.sort_by_key(|k| k.as_str() == "chain");
    for k in keys {
        let (x, y) = (
            am.get(k).cloned().unwrap_or(Value::Null),
            bm.get(k).cloned().unwrap_or(Value::Null),
        );
        if am.contains_key(k) != bm.contains_key(k) || x != y {
            return Some(Divergence {
                seq,
                field: k.clone(),
                original: if am.contains_key(k) {
                    x
                } else {
                    json!("<absent>")
                },
                replayed: if bm.contains_key(k) {
                    y
                } else {
                    json!("<absent>")
                },
            });
        }
    }
    None
}

/// Compares `replayed` with `original` from record `from` on; a replayed ledger shorter than the
/// original is compared only as far as it goes unless `complete`.
pub fn compare_from(
    original: &[Value],
    replayed: &[Value],
    from: usize,
    complete: bool,
) -> Option<Divergence> {
    let n = original.len().max(replayed.len());
    for i in from..n {
        match (original.get(i), replayed.get(i)) {
            (Some(a), Some(b)) => {
                if let Some(d) = field_diff(i as u64, a, b) {
                    return Some(d);
                }
            }
            (Some(a), None) if complete => {
                return Some(Divergence {
                    seq: i as u64,
                    field: "<record>".into(),
                    original: comparable(a),
                    replayed: json!("<absent>"),
                })
            }
            (Some(_), None) => return None,
            (None, Some(b)) => {
                return Some(Divergence {
                    seq: i as u64,
                    field: "<record>".into(),
                    original: json!("<absent>"),
                    replayed: comparable(b),
                })
            }
            (None, None) => break,
        }
    }
    None
}

/// Field-by-field comparison of two complete ledgers ignoring host fields.
pub fn compare(original: &[Value], replayed: &[Value]) -> Option<Divergence> {
    compare_from(original, replayed, 0, true)
}

/// Compares two ledger files; both are read strictly (seq, chain, truncation).
pub fn compare_files(original: &Path, replayed: &Path) -> Result<Option<Divergence>> {
    let a = Ledger::scan(original)?;
    let b = Ledger::scan(replayed)?;
    Ok(compare(&a.records, &b.records))
}

/// Everything a replay reads.
#[derive(Debug, Clone)]
pub struct ReplayInputs {
    /// The original ledger.
    pub ledger: PathBuf,
    /// The Build directory; its verified hash must equal the header's `build`.
    pub build_dir: PathBuf,
    /// The initial world state; its content hash must equal the header's `initial_state`.
    pub initial: Value,
    /// The cassette of the original's adapter traffic (required when the ledger has adapter records).
    pub cassette: Option<PathBuf>,
    /// Directory of the recorded turn scripts (`turn-<n>.py`).
    pub scripts: PathBuf,
    /// Build roots an `upgrade` record's target Build hash is resolved in (as `<root>/<hex>`),
    /// searched before the directory that holds `build_dir`.
    pub builds: Vec<PathBuf>,
    /// Instance store the replay Instance is created in.
    pub home: PathBuf,
    /// Id of the replay Instance (`--into <new-id>`, a ULID); a fresh ULID when absent.
    pub into: Option<String>,
    /// Turn options applied to every replayed turn (debug effect assertion).
    pub opts: TurnOptions,
}

/// The outcome of a replay.
#[derive(Debug, Clone)]
pub struct ReplayReport {
    /// The original Instance id, from the ledger header.
    pub original: String,
    /// The id of the new Instance the replay created.
    pub into: String,
    /// Number of records in the replayed ledger.
    pub records: usize,
    /// Number of turns re-run before the end or the first divergence.
    pub turns: u64,
    /// The first divergent record; `None` means identical except host fields.
    pub divergence: Option<Divergence>,
    /// Content hash of the replay Instance's final state.
    pub state_digest: String,
}

impl ReplayReport {
    /// The report as one JSON object, including the ignored host fields.
    pub fn to_json(&self) -> Value {
        json!({
            "original": self.original,
            "into": self.into,
            "records": self.records,
            "turns": self.turns,
            "identical": self.divergence.is_none(),
            "divergence": self.divergence.as_ref().map(Divergence::to_json),
            "state_digest": self.state_digest,
            "ignored_fields": IGNORED_FIELDS,
        })
    }
}

fn refuse(m: String) -> KernelError {
    KernelError::Refused(format!("replay: {m}"))
}

/// One step of a replay, in ledger order.
enum Step {
    /// Re-run turn `n` (1-based) from its recorded input.
    Turn(u64),
    /// Re-apply an `upgrade` record: upgrade to the Build in `target`.
    Upgrade {
        /// The verified target Build directory.
        target: PathBuf,
        /// Whether the target is experimental (the original upgrade passed
        /// `--allow-experimental`).
        experimental: bool,
    },
    /// Re-apply the `recovery` record of a restore.
    Restore,
}

/// The replay steps of `records` in ledger order, each lifecycle record checked before anything is
/// created: an upgrade target must resolve to a Build whose contents hash to `new_build`, and a
/// recovery must not close a turn a crash interrupted.
fn plan_steps(records: &[Value], roots: &[PathBuf]) -> Result<Vec<Step>> {
    let mut steps = Vec::new();
    for r in records.iter().skip(1) {
        match r["kind"].as_str().unwrap_or("") {
            "turn" => steps.push(Step::Turn(r["turn"].as_u64().unwrap_or(0))),
            "upgrade" => {
                let hash = r["new_build"].as_str().unwrap_or("");
                let dir = Build::resolve(hash, roots).map_err(|_| {
                    refuse(format!(
                        "record {} upgrades to Build {hash}, which is not under {}; pass --builds <root>",
                        r["seq"],
                        roots
                            .iter()
                            .map(|p| p.display().to_string())
                            .collect::<Vec<_>>()
                            .join(", ")
                    ))
                })?;
                let build = Build::load(&dir)?;
                if build.hash != hash {
                    return Err(KernelError::HashMismatch(format!(
                        "replay: record {} upgrades to Build {hash}, {} holds {}",
                        r["seq"],
                        dir.display(),
                        build.hash
                    )));
                }
                steps.push(Step::Upgrade {
                    target: build.dir.clone(),
                    experimental: build.experimental.is_some(),
                });
            }
            "recovery" => {
                if !r["interrupted_turn"].is_null() {
                    return Err(refuse(format!(
                        "record {} recovers turn {}, which a kernel crash interrupted; replay re-runs complete turns and cannot reproduce where a crash cut one, so replay a copy of the ledger cut before that turn",
                        r["seq"], r["interrupted_turn"]
                    )));
                }
                steps.push(Step::Restore);
            }
            _ => {}
        }
    }
    Ok(steps)
}

/// Upgrades the replay Instance to `target` through [`crate::upgrade::upgrade`] and reopens it.
fn reapply_upgrade(
    inst: Instance,
    home: &Path,
    target: &Path,
    experimental: bool,
) -> Result<Instance> {
    let id = inst.meta.id.clone();
    drop(inst);
    let opts = UpgradeOptions {
        allow_experimental: experimental,
    };
    crate::upgrade::upgrade(home, &id, target, opts).map_err(|e| match e {
        UpgradeError::Kernel(k) => k,
        other => refuse(format!(
            "re-applying the upgrade to {}: {other}",
            target.display()
        )),
    })?;
    Instance::open(home, &id)
}

/// Snapshots the replay Instance and restores that snapshot through [`Instance::restore`], which
/// appends the `recovery` record.
fn reapply_restore(mut inst: Instance, home: &Path) -> Result<Instance> {
    let snapshot = inst.snapshot()?;
    let id = inst.meta.id.clone();
    drop(inst);
    Instance::restore(home, &id, &snapshot).map(|(inst, _)| inst)
}

/// The replayed records as the original Instance would have written them. A lifecycle record's
/// `snapshot` is the hash of the replay's own snapshot file, whose bytes carry the replay
/// Instance's id and chain: it is replaced by the hash of that snapshot under `original_id` and
/// the chain this function has already rewritten at the snapshot's seq. A `recovery` record takes
/// its [`LINEAGE_FIELDS`] from the original record at the same seq. Every chain from the first
/// lifecycle record on is recomputed over the rewritten records, so a replay is identical exactly
/// when the original's chain is reproduced. Records before any lifecycle record are unchanged.
pub fn as_original(original: &[Value], original_id: &str, inst: &Instance) -> Result<Vec<Value>> {
    let snapshots = inst.dir.join("snapshots");
    let mut out: Vec<Value> = Vec::with_capacity(inst.records().len());
    let mut rechain = false;
    for (i, record) in inst.records().iter().enumerate() {
        let mut r = record.clone();
        let kind = r["kind"].as_str().unwrap_or("").to_string();
        if let (Some(m), "upgrade" | "recovery") = (r.as_object_mut(), kind.as_str()) {
            if let Some(h) = m.get("snapshot").and_then(Value::as_str) {
                let (mut snap, _) = Snapshot::load(&Snapshot::resolve(h, &snapshots))?;
                snap.instance = original_id.to_string();
                if let Some(c) = out.get(snap.seq as usize).and_then(|x| x["chain"].as_str()) {
                    snap.chain = c.to_string();
                }
                m.insert("snapshot".into(), json!(snap.hash()));
            }
            if let Some(o) = original
                .get(i)
                .filter(|o| kind == "recovery" && o["kind"] == "recovery")
            {
                for f in LINEAGE_FIELDS {
                    m.insert(f.into(), o[f].clone());
                }
            }
            rechain = true;
        }
        if rechain {
            let prev = out
                .last()
                .and_then(|x| x["chain"].as_str())
                .unwrap_or("")
                .to_string();
            let chain = chain_of(&prev, &r);
            if let Some(m) = r.as_object_mut() {
                m.insert("chain".into(), json!(chain));
            }
        }
        out.push(r);
    }
    Ok(out)
}

/// Checks the original ledger and the inputs, then replays. Nothing is created when a check fails.
pub fn replay(inp: &ReplayInputs) -> Result<ReplayReport> {
    let scan = Ledger::scan(&inp.ledger)?;
    let records = scan.records;
    let header = records
        .first()
        .ok_or_else(|| refuse("the ledger has no header".into()))?
        .clone();
    let original = header["instance"].as_str().unwrap_or("").to_string();
    if let Some(r) = records
        .iter()
        .find(|r| !REPLAYABLE_KINDS.contains(&r["kind"].as_str().unwrap_or("")))
    {
        return Err(refuse(format!(
            "record {} is a {} record; replay reproduces only {}",
            r["seq"],
            r["kind"].as_str().unwrap_or("?"),
            REPLAYABLE_KINDS.join(", ")
        )));
    }
    if !header["created_from"].is_null() {
        return Err(refuse(format!(
            "the Instance was created from snapshot {}; replay starts from an initial state",
            header["created_from"]
        )));
    }
    let build = crate::state::Build::load(&inp.build_dir)?;
    if Some(build.hash.as_str()) != header["build"].as_str() {
        return Err(KernelError::HashMismatch(format!(
            "replay: the ledger names Build {}, the directory holds {}",
            header["build"], build.hash
        )));
    }
    let initial = WorldState::from_json(&inp.initial)?;
    if Some(initial.hash().as_str()) != header["initial_state"].as_str() {
        return Err(KernelError::HashMismatch(format!(
            "replay: the ledger names initial state {}, the input hashes to {}",
            header["initial_state"],
            initial.hash()
        )));
    }
    // Turns must be 1..=T in order, each closed by exactly one turn record, each with a script.
    let turns: Vec<u64> = records
        .iter()
        .filter(|r| r["kind"] == "turn")
        .filter_map(|r| r["turn"].as_u64())
        .collect();
    if turns.iter().enumerate().any(|(i, t)| *t != i as u64 + 1) {
        return Err(refuse(format!(
            "turn records are not 1..{} in order",
            turns.len()
        )));
    }
    let last = records
        .last()
        .ok_or_else(|| refuse("the ledger has no header".into()))?;
    let boundary = ["turn", "upgrade", "recovery"];
    if records.len() > 1 && !boundary.contains(&last["kind"].as_str().unwrap_or("")) {
        return Err(refuse(format!(
            "the ledger ends inside turn {} (seq {}); recover the Instance first",
            last["turn"], last["seq"]
        )));
    }
    let mut roots = inp.builds.clone();
    if let Some(parent) = build.dir.parent() {
        roots.push(parent.to_path_buf());
    }
    let steps = plan_steps(&records, &roots)?;
    let mut inputs = Vec::new();
    for t in &turns {
        let rec = records
            .iter()
            .find(|r| r["kind"] == "turn" && r["turn"].as_u64() == Some(*t));
        inputs.push(turn_input(&inp.scripts, *t, rec)?);
    }
    let uses_adapters = records.iter().any(|r| r["kind"] == "adapter");
    if uses_adapters && inp.cassette.is_none() {
        return Err(refuse("the ledger has adapter records; replay needs the cassette of the original's adapter traffic".into()));
    }

    let opts = CreateOptions {
        seed: header["seed"].as_u64(),
        tail: Some(TailSize::from_json(&header["tail_size"])?),
        arm: header["arm"].as_str().map(str::to_string),
        model: header["model"].as_str().map(str::to_string),
        from_snapshot: None,
        initial: Some(initial.to_json()),
        allow_experimental: !header["experimental"].is_null(),
        cassette_digest: header["cassette_digest"].as_str().map(str::to_string),
    };
    let mut inst = match &inp.into {
        Some(id) => Instance::create_as(&inp.home, &inp.build_dir, opts, id)?,
        None => Instance::create(&inp.home, &inp.build_dir, opts)?,
    };
    let into = inst.meta.id.clone();
    let mut replayed = as_original(&records, &original, &inst)?;
    let mut divergence = compare_from(&records, &replayed, 0, false);
    let mut done = 0u64;
    if divergence.is_none() {
        for step in steps {
            let from = inst.records().len();
            match step {
                Step::Turn(n) => {
                    let input = inputs
                        .get((n as usize).wrapping_sub(1))
                        .ok_or_else(|| refuse(format!("turn {n} has no recorded input")))?;
                    run_recorded_turn(&mut inst, input, inp, uses_adapters)?;
                    done = n;
                }
                Step::Upgrade {
                    target,
                    experimental,
                } => inst = reapply_upgrade(inst, &inp.home, &target, experimental)?,
                Step::Restore => inst = reapply_restore(inst, &inp.home)?,
            }
            replayed = as_original(&records, &original, &inst)?;
            divergence = compare_from(&records, &replayed, from, false);
            if divergence.is_some() {
                break;
            }
        }
    }
    if divergence.is_none() {
        divergence = compare(&records, &replayed);
    }
    if let Some(d) = &divergence {
        let marker = json!({"replay_divergence": d.to_json(), "original": original, "ledger": inp.ledger.display().to_string()});
        write_atomic(
            &inst.dir.join(SEAL_FILE),
            canonical_json(&marker).as_bytes(),
        )?;
    }
    Ok(ReplayReport {
        original,
        into,
        records: inst.records().len(),
        turns: done,
        divergence,
        state_digest: inst.meta.state_hash.clone(),
    })
}

/// Re-runs one turn of the replay Instance from its recorded input: a script through the real
/// executor (gateway in replay mode when the ledger has adapter records), a protocol refusal from
/// its marker, a probe from its call list. The input is recorded again in the replay Instance.
fn run_recorded_turn(
    inst: &mut Instance,
    input: &TurnInput,
    inp: &ReplayInputs,
    uses_adapters: bool,
) -> Result<()> {
    match input {
        TurnInput::Script(script) => {
            record_script(inst, script)?;
            if uses_adapters {
                let cfg = GatewayConfig {
                    mode: Mode::Replay,
                    cassette: inp.cassette.clone(),
                    ..GatewayConfig::default()
                };
                let gw = AdapterGateway::new(cfg, inst)?;
                let mut gw = Journaled::new(gw, inst);
                run_turn(inst, script, &inp.opts, &mut gw)?;
            } else {
                let mut gw = Journaled::new(NoGateway, inst);
                run_turn(inst, script, &inp.opts, &mut gw)?;
            }
        }
        TurnInput::Refusal(v) => {
            record_refusal(inst, v)?;
            protocol::refuse(inst, v)?;
        }
        TurnInput::Probe(calls) => {
            record_probe(inst, calls)?;
            inst.probe(calls, |_| {})?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn comparison_ignores_only_host_fields() {
        let a = vec![
            json!({"seq": 0, "kind": "header", "host_ts": "x", "duration_us": 1, "instance": "A", "chain": "c0"}),
            json!({"seq": 1, "kind": "turn", "status": "ok", "host_ts": "y", "chain": "c1"}),
        ];
        let mut b = a.clone();
        b[0]["host_ts"] = json!("z");
        b[0]["instance"] = json!("B");
        b[1]["duration_us"] = json!(99);
        assert_eq!(compare(&a, &b), None);
        b[1]["status"] = json!("error");
        let d = compare(&a, &b).unwrap();
        assert_eq!((d.seq, d.field.as_str()), (1, "status"));
        assert_eq!(d.original, json!("ok"));
        assert_eq!(d.replayed, json!("error"));
        let short = &b[..1];
        let d = compare(&a, short).unwrap();
        assert_eq!((d.seq, d.field.as_str()), (1, "<record>"));
        assert!(compare_from(&a, short, 0, false).is_none());
    }

    #[test]
    fn refusal_markers_roundtrip_without_message_text() {
        for v in [
            Violation::NoBlock,
            Violation::MultipleBlocks { lines: vec![1, 5] },
            Violation::WrongLanguage {
                language: "text".into(),
                line: 3,
            },
            Violation::UnclosedFence { line: 2 },
        ] {
            assert_eq!(violation_from_json(&violation_to_json(&v)), Some(v));
        }
        assert_eq!(violation_from_json(&json!({"violation": "other"})), None);
    }

    #[test]
    fn script_paths_are_per_turn() {
        assert_eq!(
            script_path(Path::new("/i"), 7),
            PathBuf::from("/i/scripts/turn-000007.py")
        );
    }
}
